import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {createBosses,updateBoss,damageBoss} from '../js/bosses.js';
import {segmentHitsBox,handPosition,resetMatrona,clearMatrona,matronaAnimation,MATRONA_TIMING} from '../js/matrona.js';
import {buildMap,GROUND} from '../js/map.js';
const config=JSON.parse(readFileSync(new URL('../assets/bosses/matrona/config.json',import.meta.url)));
for(const a of Object.values(config.animations))if(a.enabled!==false)a.ready=true;
const context={config,platforms:buildMap().platforms};
const player=b=>({x:b.x-240,y:GROUND-54,w:30,h:54,health:100,invuln:0,dead:false});
assert.ok(segmentHitsBox({x:0,y:0},{x:100,y:100},{x:45,y:43,w:10,h:12},5));
assert.ok(!segmentHitsBox({x:0,y:0},{x:100,y:100},{x:45,y:80,w:10,h:12},5));
assert.ok(!segmentHitsBox({x:0,y:0},{x:0,y:0},{x:4,y:4,w:2,h:2},5));
assert.ok(segmentHitsBox({x:0,y:0},{x:0,y:0},{x:3,y:4,w:2,h:2},5));
for(const fps of [30,60,120]) {
 const walker=createBosses()[0],target=player(walker);
 walker.active=true;resetMatrona(walker);walker.timer=10;
 target.x=walker.x-400;walker.moveStep=-1;walker.moveTimer=1;const start=walker.x;
 for(let i=0;i<fps/2;i++)updateBoss(walker,target,1/fps,context);
 assert.ok(Math.abs(walker.x-(start-12))<1e-8);
 assert.equal(walker.facing,-1);assert.equal(matronaAnimation(walker),'walk');
 target.x=walker.x+400;walker.moveTimer=0;walker.movePause=false;updateBoss(walker,target,1/fps,context);
 assert.equal(walker.facing,1);assert.equal(matronaAnimation(walker),'walk');
 target.x=walker.x-100;walker.moveTimer=0;walker.movePause=false;const close=walker.x;updateBoss(walker,target,1/fps,context);
 assert.ok(walker.x>=close);
 walker.x=walker.arena.left+16;target.x=walker.x-400;walker.moveTimer=0;walker.movePause=false;
 updateBoss(walker,target,1/fps,context);
 assert.equal(walker.x,walker.arena.left+16);assert.equal(matronaAnimation(walker),'idle');
 walker.x=walker.arena.right-walker.w-16;target.x=walker.x+400;walker.moveTimer=0;walker.movePause=false;
 updateBoss(walker,target,1/fps,context);
 assert.equal(walker.x,walker.arena.right-walker.w-16);assert.equal(matronaAnimation(walker),'idle');
 for(const state of ['beam_telegraph','beam_lock','beam_fire','beam_recovery','quarantine_cast','quarantine_warning','quarantine_strike','quarantine_recovery']){
  walker.matronaState=state;walker.timer=1;const x=walker.x;
  updateBoss(walker,target,1/fps,context);assert.equal(walker.x,x);
  assert.equal(matronaAnimation(walker),state.startsWith('beam')?'attack_beam':'attack_quarantine');
 }
 walker.matronaState='beam_recovery';walker.timer=.001;
 updateBoss(walker,target,1/fps,context);target.x=walker.x-400;
 updateBoss(walker,target,1/fps,context);assert.equal(matronaAnimation(walker),'walk');
 const dt=1/fps,b=createBosses()[0],p=player(b);
 assert.equal(updateBoss(b,p,dt,context).kind,'intro');
 p.x=b.x-310;const original=b.x;updateBoss(b,p,dt,context);assert.notEqual(b.x,original);
 resetMatrona(b);b.active=true;b.facing=-1;b.matronaState='beam_telegraph';b.timer=MATRONA_TIMING.beamTrack;
 const hp=p.health;
 while(b.matronaState==='beam_telegraph')updateBoss(b,p,dt,context);
 assert.equal(p.health,hp);assert.equal(b.matronaState,'beam_lock');
 const lockedWarning=JSON.stringify(b.beam);p.y-=150;updateBoss(b,p,dt,context);
 assert.equal(JSON.stringify(b.beam),lockedWarning);assert.equal(p.health,hp);p.y+=150;
 while(b.matronaState==='beam_lock')updateBoss(b,p,dt,context);
 assert.equal(b.matronaState,'beam_fire');
 assert.deepEqual(b.beam.a,handPosition(b,config));
 assert.ok(b.beam.z.y>b.beam.a.y);assert.ok(segmentHitsBox(b.beam.a,b.beam.z,p,5));
 const locked=JSON.stringify(b.beam);p.y-=150;updateBoss(b,p,dt,context);assert.equal(JSON.stringify(b.beam),locked);
 p.y+=150;updateBoss(b,p,dt,context);assert.equal(p.health,hp-12);
 p.invuln=0;updateBoss(b,p,dt,context);assert.equal(p.health,hp-12);
 while(b.matronaState==='beam_fire')updateBoss(b,p,dt,context);
 assert.equal(b.matronaState,'beam_recovery');
 p.attackTimer=1;p.state='attack';p.attackHitConsumed=false;p.attackBox={...b};p.combo=0;
 const before=b.health;damageBoss(b,p);assert.ok(b.health<before);
 while(b.matronaState==='beam_recovery')updateBoss(b,p,dt,context);
 assert.equal(b.beam,null);assert.equal(b.matronaState,'idle');
 resetMatrona(b);b.matronaState='beam_fire';b.timer=.3;
 b.beam={a:{x:p.x-30,y:p.y+20},z:{x:p.x+60,y:p.y+20},radius:5,hit:false};
 p.invuln=.2;const dashHp=p.health;updateBoss(b,p,dt,context);assert.equal(p.health,dashHp);
 resetMatrona(b);b.matronaState='quarantine_cast';b.timer=.001;p.invuln=0;
 updateBoss(b,p,dt,context);const zones=JSON.stringify(b.zones),warningHp=p.health;
 assert.ok(b.zones.length>=2&&b.zones.length<=3);
 assert.ok(b.zones.every(z=>z.x>=b.arena.left&&z.x+z.w<=b.arena.right&&context.platforms.some(s=>s.y===z.y+z.h&&s.x<=z.x&&s.x+s.w>=z.x+z.w)));
 assert.ok(b.zones.reduce((n,z)=>n+z.w,0)<(b.arena.right-b.arena.left)*.5);
 while(b.matronaState==='quarantine_warning')updateBoss(b,p,dt,context);
 assert.equal(p.health,warningHp);assert.equal(JSON.stringify(b.zones),zones);
 p.x=b.zones[0].x;p.y=GROUND-p.h;updateBoss(b,p,dt,context);assert.equal(p.health,warningHp-11);
 p.invuln=0;updateBoss(b,p,dt,context);assert.equal(p.health,warningHp-11);
 while(b.matronaState!=='idle')updateBoss(b,p,dt,context);
 assert.deepEqual(b.zones,[]);
 const choices=[];resetMatrona(b);p.invuln=100;
 for(let i=0;i<fps*45;i++){const serial=b.attackSerial;updateBoss(b,p,dt,context);if(b.attackSerial!==serial)choices.push(b.lastAttack);assert.ok(b.x>=b.arena.left&&b.x+b.w<=b.arena.right)}
 assert.ok(choices.includes('beam')&&choices.includes('quarantine'));
 for(let i=2;i<choices.length;i++)assert.ok(!(choices[i]===choices[i-1]&&choices[i]===choices[i-2]));
 b.dead=true;clearMatrona(b);assert.equal(b.beam,null);assert.deepEqual(b.zones,[]);
 b.dead=false;resetMatrona(b);assert.equal(b.matronaState,'idle');assert.equal(b.attackSerial,0);
}
console.log('PASS: Matrona at 30/60/120 FPS: diagonal geometry, locked aim, damage, invulnerability, recovery, surfaces, safe space, movement, attack selection, death/reset.');
